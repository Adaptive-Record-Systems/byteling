/**
 * sync-design-bible.mjs — keep Designling's rulebook in sync with the source.
 *
 * The designReview backend function can't read the claude-skills repo at runtime
 * (it runs on Base44's servers), so its design bible has to be CARRIED in the
 * function. This script re-reads the canonical checklist docs from claude-skills
 * and regenerates the DESIGN_BIBLE block inside designReview/entry.ts — so the
 * function always carries the CURRENT bible, not a hand-copied snapshot.
 *
 *   Run whenever the bible/skills evolve, then redeploy:
 *     node scripts/sync-design-bible.mjs
 *
 * It rewrites only the region between the DESIGN_BIBLE sentinels; everything else
 * in entry.ts (the review contract, the JSON shape) is hand-maintained.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const bytelingRoot = path.resolve(scriptDir, '..');
const skillsRoot = process.env.CLAUDE_SKILLS_DIR
  ? path.resolve(process.env.CLAUDE_SKILLS_DIR)
  : path.resolve(bytelingRoot, '..', 'claude-skills');

// The four checklist/taste docs that make up the judgment layer. Order matters:
// discipline first, then the positive craft moves, then the (loose) preference
// layer and the ARS stance on it.
const SOURCES = [
  { title: 'The divine hell-nos (DISCIPLINE — binding)', file: 'shared/build-bible/lessons/divine-hell-nos.md' },
  { title: 'Anti-AI craft tells (positive moves to check for)', file: 'shared/build-bible/lessons/anti-ai-craft-tells.md' },
  { title: 'Design taste (PREFERENCE — apply loosely)', file: 'shared/build-bible/junk-drawer/design-taste.md' },
  { title: 'ARS house stance (discipline binding, preference a guide)', file: 'shared/build-bible/junk-drawer/ars-taste.md' },
];

const stripFrontmatter = (s) => s.replace(/^---\n[\s\S]*?\n---\n/, '').trim();

let bible = 'The house design bible (current, synced from claude-skills). Use this as your rulebook.\n';
for (const src of SOURCES) {
  const abs = path.join(skillsRoot, src.file);
  let raw;
  try {
    raw = readFileSync(abs, 'utf8');
  } catch {
    console.error(`\n✖ Could not read ${abs}`);
    console.error(`  Set CLAUDE_SKILLS_DIR or put claude-skills next to byteling. Aborting — entry.ts left unchanged.`);
    process.exit(1);
  }
  bible += `\n\n===== ${src.title} =====\n${stripFrontmatter(raw)}`;
}

const entryPath = path.join(bytelingRoot, 'base44', 'functions', 'designReview', 'entry.ts');
const START = '// <<<DESIGN_BIBLE (generated by scripts/sync-design-bible.mjs — do not hand-edit)>>>';
const END = '// <<<END DESIGN_BIBLE>>>';

let entry = readFileSync(entryPath, 'utf8');
const startIdx = entry.indexOf(START);
const endIdx = entry.indexOf(END);
if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
  console.error(`✖ DESIGN_BIBLE sentinels not found in ${entryPath}. Aborting.`);
  process.exit(1);
}

// JSON.stringify makes a safe double-quoted JS string literal — no template-literal
// escaping headaches for backticks / ${ } in the docs.
const block = `${START}\nconst DESIGN_BIBLE = ${JSON.stringify(bible)};\n${END}`;
entry = entry.slice(0, startIdx) + block + entry.slice(endIdx + END.length);
writeFileSync(entryPath, entry);

console.log(`✓ Synced ${SOURCES.length} docs → DESIGN_BIBLE (${bible.length.toLocaleString()} chars) in designReview/entry.ts`);
console.log('  Redeploy for the function to pick it up (deploy:live).');
